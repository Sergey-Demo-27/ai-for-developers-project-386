// Заглушка middleware валидации.
//
// Правила проверки входных данных появятся вместе с методами API, когда
// станет известен функционал проекта. Пока это прозрачный pass-through,
// чтобы можно было заранее расставить его в цепочке обработки запроса.
//
// Планируемое использование:
//   router.post('/', validate(rules), handler)
export default function validate() {
  return (req, res, next) => next();
}
